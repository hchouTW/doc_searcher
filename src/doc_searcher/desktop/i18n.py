def tr(language: str, key: str, **values: Any) -> str:
    """Return a localized and optionally formatted message."""
    resources = TRANSLATIONS.get(language, TRANSLATIONS["zh-TW"])
    template = resources.get(key, TRANSLATIONS["zh-TW"].get(key, key))
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template
